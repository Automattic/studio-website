// Finalize the composed site in dist/ for Spacefast, after the docs are copied to dist/docs.
//
// Spacefast renders every uploaded .md file as an HTML page and stops serving the file
// itself, which would take the Markdown copies of the docs pages (and llms.txt's links to
// them) offline. Each .md becomes .md.txt and a rewrite keeps the .md URL, served as
// text/markdown. Spacefast also answers 403 for dot directories, so the files Blume puts
// under .well-known move up a level, as spacefast.com/docs does, and every reference
// follows. Blume's own _headers rules fold into the root _headers, minus the ones with an
// extension wildcard (/docs/*.md), which Spacefast rejects.
//
// Usage: node docs/scripts/finalize-site.mjs dist

import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const dist = resolve(process.argv[2] ?? "dist");
const docs = join(dist, "docs");
const base = "/docs";

const walk = (dir) =>
	readdirSync(dir, { withFileTypes: true, recursive: true })
		.filter((entry) => entry.isFile())
		.map((entry) => join(entry.parentPath, entry.name));
const isText = (file) => /\.(html|json|txt|md|mdx|xml)$/.test(file);

// 1. .well-known → the docs root.
const wellKnown = join(docs, ".well-known");
let moved = 0;
if (existsSync(wellKnown)) {
	for (const file of walk(wellKnown)) {
		const target = join(docs, relative(wellKnown, file));
		mkdirSync(dirname(target), { recursive: true });
		renameSync(file, target);
		moved++;
	}
	rmSync(wellKnown, { recursive: true, force: true });
}
for (const file of walk(docs).filter(isText)) {
	const text = readFileSync(file, "utf8");
	const next = text.replaceAll(`${base}/.well-known/`, `${base}/`);
	if (next !== text) writeFileSync(file, next);
}

// 2. .md → .md.txt, with a rewrite and a content type for the .md URL.
const rewrites = [];
const headers = [];
for (const file of walk(docs).filter((f) => f.endsWith(".md"))) {
	const route = `${base}/${relative(docs, file).split("\\").join("/")}`;
	renameSync(file, `${file}.txt`);
	rewrites.push(`${route}  ${route}.txt  200`);
	headers.push(`${route}\n  Content-Type: text/markdown; charset=utf-8`);
}

// 3. Headers: Blume's rules without the extension wildcards, then the Markdown ones.
const blumeHeaders = join(docs, "_headers");
const kept = [];
if (existsSync(blumeHeaders)) {
	let keep = true;
	for (const line of readFileSync(blumeHeaders, "utf8").replaceAll(`${base}/.well-known/`, `${base}/`).split("\n")) {
		if (line.startsWith("/")) keep = !/\*\./.test(line);
		if (keep && line.trim()) kept.push(line);
	}
}
appendFileSync(join(dist, "_headers"), `\n# Docs (generated by Blume)\n${kept.join("\n")}\n\n# Markdown copies of the docs pages\n${headers.join("\n")}\n`);
appendFileSync(join(dist, "_redirects"), `\n# Markdown copies of the docs pages (Spacefast would render a .md file as a page)\n${rewrites.join("\n")}\n`);

// 4. Files Spacefast doesn't read under /docs.
for (const name of ["_headers", "robots.txt", "vercel.json", "blume-redirects.json"]) rmSync(join(docs, name), { force: true });

console.log(`Finalized dist/docs: ${moved} files out of .well-known, ${rewrites.length} Markdown copies behind rewrites, ${kept.filter((l) => l.startsWith("/")).length} Blume header rules kept.`);
